#!/data/data/com.termux/files/usr/bin/env bash
# ============================================================
#  پک v2.0 — مدیر بستهٔ ساده و فارسی برای ترموکس
#  استفاده: پک <دستور> [آرگومان‌ها]
#  دستورات: نصب | حذف | جستجو | فهرست | نصب‌شده | اطلاعات |
#           به‌روزرسانی | ارتقا | پاکسازی | نگهداری | راهنما | نسخه
# ============================================================

set -u

# ---- ثابت‌ها ----
VERSION="2.0.0"
CACHE_FILE="$HOME/.cache/pak-last-update"

# ---- خروجی رنگی ----
اگر_رنگ() { [ -t 1 ]; }
آبی()   { اگر_رنگ && printf '\033[1;36m▸ %s\033[0m\n' "$*" || printf '▸ %s\n' "$*"; }
موفق()  { اگر_رنگ && printf '\033[1;32m✓ %s\033[0m\n' "$*" || printf '✓ %s\n' "$*"; }
هشدار() { اگر_رنگ && printf '\033[1;33m! %s\033[0m\n' "$*" || printf '! %s\n' "$*"; }
خطا()   { اگر_رنگ && printf '\033[1;31m✗ %s\033[0m\n' "$*" || printf '✗ %s\n' "$*"; }

خاموش() {
  خطا "$*"
  printf 'راهنما: پک راهنما\n'
  exit 1
}

در_ترموکس_هستیم() {
  [ -n "${TERMUX_VERSION:-}" ] || [ -d "/data/data/com.termux" ]
}

# ---- به‌روزرسانی هوشمند مخازن (حداکثر هر ۷ روز) ----
مخازن_تازه_نیاز_دارد() {
  local now last age
  now="$(date +%s)"
  mkdir -p "$(dirname "$CACHE_FILE")" 2>/dev/null
  last="$(cat "$CACHE_FILE" 2>/dev/null || echo 0)"
  age=$(( now - last ))
  [ "$age" -gt 604800 ]   # ۷ روز
}

مخازن_تازه_کن() {
  if مخازن_تازه_نیاز_دارد; then
    آبی "به‌روزرسانی فهرست بسته‌ها (هر هفته یک بار)..."
    apt update -y >/dev/null 2>&1 && date +%s > "$CACHE_FILE" \
      || هشدار "به‌روزرسانی مخازن انجام نشد؛ ادامه می‌دهم."
  fi
}

# ---- دستورات ----

نصب() {
  [ -z "${1:-}" ] && خاموش "نام بسته را وارد کنید. مثال: پک نصب python"
  در_ترموکس_هستیم || هشدار "خارج از ترموکس اجرا شده؛ ممکن است کار نکند."
  مخازن_تازه_کن
  آبی "در حال نصب بسته: $1"
  if apt install -y "$1"; then
    موفق "بستهٔ «$1» با موفقیت نصب شد."
  else
    خطا "نصب «$1» ناموفق بود. املای نام بسته را بررسی کنید: پک جستجو ${1:0:4}"
    exit 1
  fi
}

حذف_بسته() {
  [ -z "${1:-}" ] && خاموش "نام بسته را وارد کنید. مثال: پک حذف nano"
  آبی "در حال حذف بسته: $1"
  if apt remove -y "$1"; then
    موفق "بستهٔ «$1» حذف شد."
  else
    خطا "حذف «$1» ناموفق بود."
    exit 1
  fi
}

جستجو() {
  [ -z "${1:-}" ] && خاموش "عبارت جستجو را وارد کنید. مثال: پک جستجو python"
  آبی "نتایج جستجو برای: $1"
  apt search "$1" 2>/dev/null | head -40 || خطا "چیزی پیدا نشد."
}

فهرست_نصب‌شده() {
  آبی "بسته‌های نصب‌شده روی این دستگاه:"
  dpkg --get-selections 2>/dev/null | awk '$2=="install"{print $1}' | sort | more
}

اطلاعات() {
  [ -z "${1:-}" ] && خاموش "نام بسته را وارد کنید. مثال: پک اطلاعات git"
  apt show "$1" 2>/dev/null || { خطا "بستهٔ «$1» پیدا نشد."; exit 1; }
}

به‌روزرسانی() {
  آبی "به‌روزرسانی فهرست بسته‌ها..."
  apt update -y && { date +%s > "$CACHE_FILE" 2>/dev/null; موفق "فهرست بسته‌ها به‌روز شد."; } \
    || { خطا "به‌روزرسانی ناموفق بود (اینترنت را بررسی کنید)."; exit 1; }
}

ارتقا() {
  آبی "ارتقای بسته‌های نصب‌شده..."
  apt upgrade -y && موفق "همهٔ بسته‌ها به‌روز شدند." \
    || { خطا "ارتقا ناموفق بود."; exit 1; }
}

پاکسازی() {
  آبی "پاک‌سازی بسته‌های بی‌استفاده و کش..."
  apt autoremove -y && apt clean && موفق "پاک‌سازی انجام شد."
}

نگهداری() {
  به‌روزرسانی && ارتقا && پاکسازی && موفق "نگهداری کامل انجام شد. دستگاه اکنون به‌روز است."
}

راهنما() {
  cat <<EOF
پک v$VERSION — مدیر بستهٔ فارسی ترموکس

استفاده:
  پک <دستور> [آرگومان]

دستورات:
  نصب <بسته>        نصب یک بسته            مثال: پک نصب python
  حذف <بسته>        حذف یک بسته            مثال: پک حذف nano
  جستجو <عبارت>     جستجوی بسته            مثال: پک جستجو git
  اطلاعات <بسته>    مشخصات یک بسته
  فهرست | نصب‌شده   لیست بسته‌های نصب‌شده
  به‌روزرسانی        به‌روزرسانی فهرست بسته‌ها
  ارتقا             ارتقای همهٔ بسته‌ها
  پاکسازی           پاک‌سازی کش و بسته‌های بی‌استفاده
  نگهداری           به‌روزرسانی + ارتقا + پاکسازی (یک دستور)
  راهنما            همین راهنما
  نسخه              نمایش شمارهٔ نسخه
EOF
}

# ---- مسیریابی دستورات (فارسی و انگلیسی) ----
case "${1:-}" in
  نصب|install)            shift; نصب "$@" ;;
  حذف|remove)             shift; حذف_بسته "$@" ;;
  جستجو|search)           shift; جستجو "$@" ;;
  اطلاعات|info)           shift; اطلاعات "$@" ;;
  فهرست|نصب‌شده|list)     فهرست_نصب‌شده ;;
  به‌روزرسانی|update)     به‌روزرسانی ;;
  ارتقا|upgrade)          ارتقا ;;
  پاکسازی|clean)          پاکسازی ;;
  نگهداری|maintenance)    نگهداری ;;
  راهنما|help|-h|--help)  راهنما ;;
  نسخه|version|-v)        echo "پک v$VERSION" ;;
  "")                     راهنما ;;
  *)                      خاموش "دستور ناشناخته: «$1»" ;;
esac
