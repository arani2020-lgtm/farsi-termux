#!/data/data/com.termux/files/usr/bin/bash
# پک — مدیر بستهٔ ساده و فارسی برای ترموکس
# استفاده: پک نصب <بسته> | پک حذف <بسته> | پک جستجو <عبارت> | پک به‌روزرسانی | پک فهرست | پک نصب‌شده | پک پاکسازی

س() { printf '\033[1;36m%s\033[0m\n' "$*"; }
موفق() { printf '\033[1;32m✓ %s\033[0m\n' "$*"; }
خطا() { printf '\033[1;31m✗ %s\033[0m\n' "$*" >&2; exit 1; }
هشدار() { printf '\033[1;33m! %s\033[0m\n' "$*"; }

اگر_root_نیست() {
  if [ "$(id -u)" -ne 0 ] && ! command -v termux-info >/dev/null 2>&1; then
    خطا "این اسکریپت باید داخل ترموکس اجرا شود."
  fi
}

فهرست() {
  s "بسته‌های نصب‌شده روی این دستگاه:"
  dpkg --get-selections 2>/dev/null | awk '$2=="install"{print $1}' | sort
}

نصب() {
  [ -z "$1" ] && خطا "نام بسته را وارد کنید. مثال: پک نصب ترمیم"
  s "در حال آماده‌سازی مخازن..."
  apt update -y >/dev/null 2>&1 || هشدار "به‌روزرسانی مخازن انجام نشد؛ ادامه می‌دهم."
  s "در حال نصب بسته: $1"
  if apt install -y "$1"; then موفق "بستهٔ $1 با موفقیت نصب شد."; else خطا "نصب $1 ناموفق بود."; fi
}

حذف() {
  [ -z "$1" ] && خطا "نام بسته را وارد کنید. مثال: پک حذف nano"
  s "در حال حذف بسته: $1"
  if apt remove -y "$1"; then موفق "بستهٔ $1 حذف شد."; else خطا "حذف $1 ناموفق بود."; fi
}

جستجو() {
  [ -z "$1" ] && خطا "عبارت جستجو را وارد کنید. مثال: پک جستجو python"
  s "نتایج جستجو برای: $1"
  apt search "$1" 2>/dev/null | head -60
}

به‌روزرسانی() {
  s "در حال به‌روزرسانی فهرست بسته‌ها..."
  apt update -y && موفق "فهرست بسته‌ها به‌روز شد."
}

بروزرسانی_بسته‌ها() {
  s "در حال ارتقای بسته‌های نصب‌شده..."
  apt upgrade -y && موفق "همهٔ بسته‌ها به‌روز شدند."
}

پاکسازی() {
  s "در حال پاک‌سازی بسته‌های بی‌استفاده و کش..."
  apt autoremove -y && apt clean && موفق "پاک‌سازی انجام شد."
}

اطلاعات() {
  [ -z "$1" ] && خطا "نام بسته را وارد کنید. مثال: پک اطلاعات git"
  apt show "$1" 2>/dev/null || خطا "بستهٔ $1 پیدا نشد."
}

راهنما() {
  cat << 'راهنما'
پک — مدیر بستهٔ فارسی برای ترموکس

استفاده:  پک <دستور> [گزینه]

دستورها:
  نصب <بسته>        نصب یک بسته (مثال: پک نصب git)
  حذف <بسته>        حذف یک بسته
  جستجو <عبارت>     جستجو میان بسته‌ها
  اطلاعات <بسته>    نمایش اطلاعات یک بسته
  فهرست             نمایش بسته‌های نصب‌شده
  به‌روزرسانی         به‌روزرسانی فهرست مخازن
  ارتقا             ارتقای همهٔ بسته‌های نصب‌شده
  پاکسازی           حذف وابستگی‌های بی‌استفاده
  راهنما            نمایش این پیام

میان‌برهای فارسی جایگزین دستورهای طولانی ترموکس هستند:
  پک نصب فایل.deb      نصب بستهٔ محلی
راهنما
}

case "$1" in
  نصب)           shift; [ "${1##*.}" = "deb" ] && apt install -y "./$1" || نصب "$1" ;;
  حذف)           shift; حذف "$1" ;;
  جستجو)         shift; جستجو "$1" ;;
  اطلاعات)       shift; اطلاعات "$1" ;;
  فهرست)         فهرست ;;
  به‌روزرسانی)   به‌روزرسانی ;;
  ارتقا)         بروزرسانی_بسته‌ها ;;
  پاکسازی)       پاکسازی ;;
  راهنما|-h|--help|"") راهنما ;;
  *)             خطا "دستور ناشناخته: $1 — برای راهنما «پک راهنما» را اجرا کنید." ;;
esac
