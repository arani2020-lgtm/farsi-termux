# ---- توابع بیشتر ----
# باز کردن فایل در ویرایشگر
بازکن() { ${EDITOR:-nano} "$@"; }

# ایجاد پوشه و ورود به آن
بساز() {
  mkdir -p "$1" && cd "$1" && echo "پوشهٔ $1 ساخته شد و وارد آن شدید."
}

# فشرده‌سازی
فشرده() {
  [ -z "$1" ] && { echo "استفاده: فشرده <نام> [فایل‌ها]"; return 1; }
  tar -czf "$1.tar.gz" "${@:2}" && echo "✓ $1.tar.gz ساخته شد."
}

# استخراج
بازکن_بسته() {
  tar -xzf "$1" && echo "✓ $1 باز شد."
}

